export function localizeTool(tool, lang = "ru") {
  if (!tool) return null;
  return {
    ...tool,
    title: localizedValue(tool, "title", lang),
    subtitle: localizedValue(tool, "subtitle", lang),
    description: localizedValue(tool, "description", lang),
  };
}

export function localizeGroup(group, lang = "ru") {
  if (!group) return null;
  return {
    ...group,
    title: localizedValue(group, "title", lang),
  };
}

export function getToolsByGroup(groupId, lang = "ru") {
  return CREATE_TOOLS
    .filter(tool => tool.category === groupId)
    .map(tool => localizeTool(tool, lang));
}

export function getToolGroups(lang = "ru") {
  return TOOL_GROUPS.map(group => localizeGroup(group, lang));
}

export function getCreateTools(lang = "ru") {
  return CREATE_TOOLS.map(tool => localizeTool(tool, lang));
}

export function findTool(id, lang = "ru") {
  return localizeTool(CREATE_TOOLS.find(tool => tool.id === id) || null, lang);
}
