function pickLang(lang = "ru") {
  return String(lang || "ru").toLowerCase().startsWith("en") ? "en" : "ru";
}

function localizedValue(item = {}, key, lang = "ru") {
  const l = pickLang(lang);
  return item[`${key}_${l}`] || item[key] || "";
}

